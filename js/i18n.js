let currentLang = 'en';
const listeners = new Set();

export const getLang = () => currentLang;
export const isRtl = () => currentLang === 'ar';

/* Texts the owner edits in the "Texts" tab of the content sheet. Only keys that already exist in `translations.en`
 * are accepted, and they are always written to the page as text (never as HTML). Missing/empty = the built-in text. */
let overrides = { en: {}, ar: {} };

/** Escape a translated string before it is put inside an HTML template. */
export const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

export function t(key, vars = {}) {
  const raw = overrides[currentLang]?.[key] ?? translations[currentLang]?.[key] ?? translations.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** Read a possibly-bilingual field from a data item: item[field_ar] in Arabic, else item[field]. */
export function pick(item, field) {
  if (currentLang === 'ar') {
    const ar = item?.[`${field}_ar`];
    if (typeof ar === 'string' && ar.trim()) return ar;
  }
  const v = item?.[field];
  return typeof v === 'string' ? v : '';
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n, { year: new Date().getFullYear() }); });
  root.querySelectorAll('[data-i18n-aria]').forEach((n) => n.setAttribute('aria-label', t(n.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-alt]').forEach((n) => n.setAttribute('alt', t(n.dataset.i18nAlt)));
  root.querySelectorAll('[data-i18n-title]').forEach((n) => n.setAttribute('title', t(n.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((n) => n.setAttribute('placeholder', t(n.dataset.i18nPlaceholder)));
}

export function setLang(lang, { persist = true } = {}) {
  if (!SUPPORTED.includes(lang)) lang = 'en';
  currentLang = lang;
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';
  const suffix = html.dataset.page ? `.${html.dataset.page}` : '';
  document.title = t(`meta.title${suffix}`);
  document.querySelector('meta[name="description"]')?.setAttribute('content', t(`meta.description${suffix}`));
  applyTranslations();
  document.querySelectorAll('[data-lang]').forEach((b) => {
    const active = b.dataset.lang === lang;
    b.setAttribute('aria-pressed', String(active));
    b.classList.toggle('is-active', active);
  });
  if (persist) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage unavailable */ }
  }
  listeners.forEach((fn) => fn(lang));
}

/** rows: [{ key, text, text_ar }] from the sheet. Applies them and refreshes the page text. */
export function setTextOverrides(rows) {
  const next = { en: {}, ar: {} };
  (Array.isArray(rows) ? rows : []).forEach((r) => {
    if (!r || typeof r.key !== 'string' || !CONFIG.EDITABLE_TEXTS.some((e) => e.key === r.key) || !Object.prototype.hasOwnProperty.call(translations.en, r.key)) return;
    ['en', 'ar'].forEach((l) => {
      const v = l === 'en' ? r.text : r.text_ar;
      if (typeof v === 'string' && v.trim() && v.length <= 400) next[l][r.key] = v.trim();
    });
  });
  overrides = next;
  const suffix = document.documentElement.dataset.page ? `.${document.documentElement.dataset.page}` : '';
  document.title = t(`meta.title${suffix}`);
  applyTranslations();
}

export function initI18n() {
  let lang = 'en';
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(stored)) lang = stored;
  } catch { /* storage unavailable */ }
  const fromUrl = new URLSearchParams(window.location.search).get('lang');
  if (SUPPORTED.includes(fromUrl)) lang = fromUrl;
  setLang(lang, { persist: false });
  // The owner's own wording (Texts tab). The built-in text shows first and is swapped when the sheet answers.
  loadTexts().then((rows) => { if (rows.length) setTextOverrides(rows); }).catch(() => {});
  applyRememberedMenu();
  loadMenu().then((rows) => applyMenu(rows)).catch(() => {});
  // WhatsApp and social links from the sheet; the links on the page are redrawn when they differ from config.js.
  loadContact().then((rows) => { if (applyContact(rows)) document.dispatchEvent(new CustomEvent('plv:contact')); }).catch(() => {});
}
